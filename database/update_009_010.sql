INSERT INTO permissions (nama_permission, modul) VALUES
    ('kelola_permintaan', 'PERSEDIAAN'),
    ('setujui_permintaan', 'PERSEDIAAN'),
    ('kelola_penerimaan', 'PERSEDIAAN'),
    ('konfirmasi_penerimaan', 'PERSEDIAAN'),
    ('kelola_retur_pembelian', 'PERSEDIAAN')
ON CONFLICT (nama_permission) DO NOTHING;
INSERT INTO role_permissions (id_role, id_permission)
    SELECT DISTINCT r.id_role, p.id_permission FROM roles r
    JOIN role_permissions rp ON rp.id_role = r.id_role
    JOIN permissions kelola ON kelola.id_permission = rp.id_permission AND kelola.nama_permission = 'kelola_pengadaan'
    JOIN permissions p ON p.nama_permission IN
        ('kelola_permintaan','setujui_permintaan','kelola_penerimaan','konfirmasi_penerimaan','kelola_retur_pembelian')
    WHERE NOT EXISTS (SELECT 1 FROM role_permissions x
        WHERE x.id_role = r.id_role AND x.id_permission = p.id_permission);
