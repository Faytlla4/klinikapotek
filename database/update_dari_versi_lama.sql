-- UPDATE incremental untuk database teman (yang SUDAH berisi data lama).
-- Sifat: IDEMPOTEN â€” aman dijalankan berulang; data/tabel lama TIDAK
-- dihapus dan TIDAK diubah, hanya MENAMBAHKAN yang belum ada.
-- Asumsi: database bernama apotek dengan struktur versi lama
-- (sebelum tabel pengadaan + kolom dokter.id_user/pasien.id_user +
-- permission View per-context). Untuk database KOSONG gunakan
-- database/apotek_latest.sql, BUKAN file ini.
-- Cara pakai:
--   psql -U postgres -d apotek -v ON_ERROR_STOP=1 -f database/update_dari_versi_lama.sql
-- Isi:
--   1. Tabel pengadaan (7 tabel, IF NOT EXISTS + constraint DO-block)
--   2. Kolom dokter.id_user & pasien.id_user (IF NOT EXISTS)
--   3. Permission View per-context + Bonfire (ON CONFLICT DO NOTHING)
--   4. Grants per role berbasis NAMA (ON CONFLICT DO NOTHING)
--   5. Bersih-bersih permission View usang (aman: WHERE + hanya baris itu)
--   6. Seed portal pasien (hanya bila user id 5 ada & belum punya pasien)
--   7. Sinkron sequence (MAX, aman di semua kondisi)
-- CATATAN PENTING:
--   - Grants memakai nama_role (ADMIN_PELAYANAN/DOKTER/APOTEKER). Bila nama
--     role di tempat teman berbeda, sesuaikan Bagian 4.
--   - Setelah update, user DOKTER harus dipetakan: UPDATE dokter SET
--     id_user = <id user dokter> WHERE ...; (portal pasien butuh
--     pasien.id_user yang menunjuk user pasiennya).
-- =====================================================================

