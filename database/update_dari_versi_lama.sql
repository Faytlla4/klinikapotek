CREATE TABLE IF NOT EXISTS public.master_satuan (
    id_satuan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_satuan character varying(100) NOT NULL UNIQUE,
    status character varying(20) DEFAULT 'AKTIF' NOT NULL,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_satuan_status CHECK (status IN ('AKTIF', 'NONAKTIF'))
);
